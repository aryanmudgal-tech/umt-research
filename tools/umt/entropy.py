"""Entropy generation and the thermodynamic state index in high-cycle metal fatigue.

The material-point model of Lee & Basaran, "Predicting high cycle fatigue life
with unified mechanics theory", Mech. Mater. 164 (2022) 104116. Equation
numbers below are that paper's.

Under a cyclic stress below the macroscopic yield stress, the entropy that
matters is the one generated by micro-plasticity at defect sites (Eq. 29), so
the thermodynamic state index (TSI) is

    Phi = 1 - exp(-ds * m_s / R)                                    (Eq. 5, Phi_cr = 1)
    ds  = (1/rho) * integral of Phi * f_v * (sigma_mu : d eps_p_mu) / T     (Eqs. 27, 30)

with the micro stress and micro plastic strain from the two-scale localisation
law and linear kinematic hardening (Eqs. 21, 23, 25, 26), and the temperature
from Eq. 33. ds is therefore not a constant to look up: it is accumulated cycle
by cycle from the stress the material is put through.

Uniaxial reduction. The macro stress is S along one axis and the micro plastic
strain is deviatoric, ep * diag(1, -1/2, -1/2). Then

    von Mises micro stress      s_eq = S - (3/2) C ep,   C = 2 mu (1 - b)(1 - f_v)
    back stress (uniaxial)      h * ep
    yield                       |s_eq - h ep| = sigma_y  (the micro yield stress)
    sigma_mu : d eps_p_mu       = s_eq * d ep

so the macro stress sees a plastic modulus (3/2) C + h. Fully reversed cycling
at amplitude S_a settles into a closed loop of plastic strain range
2 (S_a - sigma_y) / ((3/2) C + h), which dissipates

    W = 4 sigma_y (S_a - sigma_y) / ((3/2) C + h)       per cycle, per unit volume of inclusion,

and nothing at all when S_a is below the micro yield stress: that is the
endurance limit.

What follows from the two equations at the top. With c = f_v W / T the entropy
generated per cycle at Phi = 1, and k = m_s / (rho R),

    d/dN [ Phi / (1 - Phi) ] = k c * Phi / (1 - Phi),

so the ODDS of the TSI grow exponentially with the number of cycles. Two things
follow. A TSI of exactly zero never moves, so the material needs a starting
value (the paper: "we first assume a small starting phi value"); and the life
at constant temperature is

    N_f = ln( odds(Phi_cr) / odds(Phi_0) ) * rho R T / (m_s f_v W),

an S-N curve in 1 / (S_a - sigma_y), with the same entropy at failure whatever
the stress amplitude - the fatigue fracture entropy the paper reports.

The one number the paper does not give is that starting TSI. PAPER_SEED below
is fitted so that the 300 MPa life equals the paper's 1.4e5 cycles; the 275
and 325 MPa lives are then predictions, and land within 4 % of the paper's.

Units: SI (Pa, kg, m, s, K, J). Entropy is per unit volume, J/(K m^3), as the
paper plots it; ds = entropy / density. Deterministic and offline.
"""

import math
from dataclasses import dataclass

GAS_CONSTANT = 8.314  # J/(mol K)


@dataclass(frozen=True)
class FatigueMaterial:
    """What the entropy model needs to know about a metal."""

    elastic_modulus: float  # Pa
    poisson_ratio: float
    hardening_modulus: float  # Pa, linear kinematic hardening of the inclusions
    density: float  # kg/m^3
    specific_heat: float  # J/(kg K)
    thermal_time: float  # s, time representative of the thermal exchanges (tau_eq)
    micro_yield: float  # Pa, microscopic yield stress = the mean fatigue limit
    defect_fraction: float  # f_v, the fraction of sites that can go micro-plastic
    molar_mass: float  # kg/mol

    @property
    def shear_modulus(self):
        return self.elastic_modulus / (2 * (1 + self.poisson_ratio))

    @property
    def bulk_modulus(self):
        return self.elastic_modulus / (3 * (1 - 2 * self.poisson_ratio))

    @property
    def localisation_modulus(self):
        """C = 2 mu (1 - b)(1 - f_v) of Eq. 21, with b from Eq. 20."""
        mu, K = self.shear_modulus, self.bulk_modulus
        b = 6 * (K + 2 * mu) / (5 * (3 * K + 4 * mu))
        return 2 * mu * (1 - b) * (1 - self.defect_fraction)

    @property
    def plastic_modulus(self):
        """d(macro stress) / d(micro plastic strain) while an inclusion yields."""
        return 1.5 * self.localisation_modulus + self.hardening_modulus

    @property
    def entropy_scale(self):
        """k = m_s / (rho R), so that Phi = 1 - exp(-k * entropy per unit volume)."""
        return self.molar_mass / (self.density * GAS_CONSTANT)


# Tables 1 and 2 of the paper, and f_v = 10 % from its section 3.6.
DP600 = FatigueMaterial(
    elastic_modulus=210e9,
    poisson_ratio=0.3,
    hardening_modulus=1000e6,
    density=7894.0,
    specific_heat=460.0,
    thermal_time=80.0,
    micro_yield=260e6,
    defect_fraction=0.10,
    molar_mass=55.85e-3,
)

PAPER_SEED = 1.769e-4  # starting TSI; fitted, see the module docstring
PAPER_CRITICAL = 0.995  # "we consider the specimen is failed when phi reaches 0.995"
PAPER_AMBIENT = 300.0  # K, where the paper's temperature curves start
PAPER_FREQUENCY = 30.0  # Hz


def plastic_work_per_cycle(material, stress_amplitude):
    """Work dissipated per cycle in a unit volume of inclusion, stabilised loop.

    Zero at or below the micro yield stress: the inclusions stay elastic.
    """
    over = abs(stress_amplitude) - material.micro_yield
    if over <= 0:
        return 0.0
    return 4 * material.micro_yield * over / material.plastic_modulus


def plastic_work_by_return_mapping(material, stress_amplitude, steps=2000, cycles=4):
    """The same work by stepping Eqs. 21, 23, 25 and 26 through a sine cycle.

    Slower than the closed form and independent of it: this is the paper's
    incremental scheme, and it is here to check the loop algebra, not to be used.
    """
    C, X = material.localisation_modulus, material.plastic_modulus
    plastic_strain = 0.0
    work = 0.0
    for _ in range(cycles):  # the loop closes after the first reversal
        work = 0.0
        for i in range(1, steps + 1):
            stress = stress_amplitude * math.sin(2 * math.pi * i / steps)
            trial = stress - X * plastic_strain  # sqrt(3/2) |A*| of Eq. 24, signed
            if abs(trial) > material.micro_yield:
                increment = math.copysign((abs(trial) - material.micro_yield) / X, trial)
                plastic_strain += increment
                work += (stress - 1.5 * C * plastic_strain) * increment
    return work


def state_index(material, entropy, initial=0.0):
    """TSI after `entropy` J/(K m^3) has been generated, starting from `initial`.

    With initial = 0 this is Eq. 5: 1 - exp(-ds m_s / R), ds = entropy / density.
    """
    return 1 - (1 - initial) * math.exp(-material.entropy_scale * entropy)


def entropy_generated(material, index, initial=0.0):
    """Inverse of state_index: the entropy that takes the TSI from initial to index."""
    return math.log((1 - initial) / (1 - index)) / material.entropy_scale


def _odds(index):
    return index / (1 - index)


def _from_odds(odds):
    return odds / (1 + odds)


def steady_temperature(material, index, work, frequency, ambient):
    """Where Eq. 33 settles for a given TSI: heating by micro-plastic work
    against relaxation to ambient over the thermal time."""
    heating = index * material.defect_fraction * work * frequency  # W/m^3
    return ambient + heating * material.thermal_time / (material.density * material.specific_heat)


def advance(material, index, temperature, work, frequency, cycles, ambient):
    """Carry the TSI and the temperature through `cycles` cycles of constant loop work.

    The TSI's odds grow by exp(k f_v W cycles / T), exactly for a constant
    temperature; the temperature relaxes toward its steady value, exactly for
    a constant TSI. Each is advanced with the other at its mid-block value, so
    keep the block short enough that neither moves much (see `simulate`).

    Returns (index, temperature).
    """
    if work <= 0 or index <= 0:
        target = ambient
        decay = math.exp(-cycles / (frequency * material.thermal_time))
        return index, target + (temperature - target) * decay

    decay = math.exp(-cycles / (frequency * material.thermal_time))
    rate = material.entropy_scale * material.defect_fraction * work
    new_index, new_temperature = index, temperature
    for _ in range(3):  # fixed point on the mid-block values; converges at once
        mid_index = 0.5 * (index + new_index)
        mid_temperature = 0.5 * (temperature + new_temperature)
        target = steady_temperature(material, mid_index, work, frequency, ambient)
        new_temperature = target + (temperature - target) * decay
        new_index = _from_odds(_odds(index) * math.exp(rate * cycles / mid_temperature))
    return new_index, new_temperature


def cycles_to_reach(material, index, target_index, work, temperature):
    """Cycles for the TSI to climb from index to target_index at a fixed temperature."""
    rate = material.entropy_scale * material.defect_fraction * work / temperature
    return math.log(_odds(target_index) / _odds(index)) / rate


def isothermal_life(material, stress_amplitude, initial=PAPER_SEED, critical=PAPER_CRITICAL, temperature=PAPER_AMBIENT):
    """Closed-form cycles to failure when the temperature is held constant.

    math.inf below the endurance limit.
    """
    work = plastic_work_per_cycle(material, stress_amplitude)
    if work <= 0:
        return math.inf
    return cycles_to_reach(material, initial, critical, work, temperature)


def simulate(
    material,
    stress_amplitude,
    frequency=PAPER_FREQUENCY,
    initial=PAPER_SEED,
    critical=PAPER_CRITICAL,
    ambient=PAPER_AMBIENT,
    max_cycles=1e9,
    max_step=0.01,
):
    """Fatigue of one material point under a constant fully reversed stress amplitude.

    Blocks of cycles are sized so the TSI rises by at most `max_step` in each,
    which keeps the temperature coupling of `advance` accurate; the last block
    is sized to land on `critical`.

    Returns a dict:
        cycles_to_failure   float, or None for a run-out (below the endurance
                            limit, or `max_cycles` reached first)
        entropy_at_failure  J/(K m^3), None for a run-out
        work_per_cycle      J/m^3 per cycle per unit volume of inclusion
        history             [{"cycles", "index", "entropy", "temperature"}, ...]
    """
    if not 0 < initial < critical < 1:
        raise ValueError(
            f"need 0 < initial TSI < critical TSI < 1, got {initial} and {critical}: "
            "a TSI of exactly zero generates no entropy and never moves"
        )
    work = plastic_work_per_cycle(material, stress_amplitude)
    index, temperature, cycles = initial, ambient, 0.0

    def point():
        return {
            "cycles": cycles,
            "index": index,
            "entropy": entropy_generated(material, index, initial),
            "temperature": temperature,
        }

    history = [point()]
    if work <= 0:
        return {"cycles_to_failure": None, "entropy_at_failure": None, "work_per_cycle": 0.0, "history": history}

    while index < critical and cycles < max_cycles:
        target = min(index + max_step, critical)
        # twice: the first guess is at the block's starting temperature
        block = cycles_to_reach(material, index, target, work, temperature)
        _, ahead = advance(material, index, temperature, work, frequency, block, ambient)
        block = cycles_to_reach(material, index, target, work, 0.5 * (temperature + ahead))
        block = min(block, max_cycles - cycles)
        index, temperature = advance(material, index, temperature, work, frequency, block, ambient)
        if target == critical and block < max_cycles - cycles:
            index = critical  # land on it rather than a rounding error short of it
        cycles += block
        history.append(point())

    failed = index >= critical
    return {
        "cycles_to_failure": cycles if failed else None,
        "entropy_at_failure": entropy_generated(material, critical, initial) if failed else None,
        "work_per_cycle": work,
        "history": history,
    }


def simulate_cycle_by_cycle(
    material,
    stress_amplitude,
    frequency=PAPER_FREQUENCY,
    initial=PAPER_SEED,
    critical=PAPER_CRITICAL,
    ambient=PAPER_AMBIENT,
    max_cycles=5_000_000,
):
    """The same fatigue life by adding Eq. 27 and Eq. 33 up one cycle at a time.

    No closed forms and no blocks, so it is slow and it is the reference the
    block scheme is tested against. Returns cycles to failure, or None.
    """
    work = plastic_work_per_cycle(material, stress_amplitude)
    if work <= 0:
        return None
    heat = material.defect_fraction * work
    capacity = material.density * material.specific_heat
    relax = 1 / (frequency * material.thermal_time)
    entropy, temperature = 0.0, ambient
    for cycle in range(int(max_cycles)):
        index = state_index(material, entropy, initial)
        if index >= critical:
            return cycle
        entropy += index * heat / temperature
        temperature += index * heat / capacity - (temperature - ambient) * relax
    return None
